<?php

use Modules\ZabbixDatabaseExport\Lib\{BackupFile, SqlExport, PostgresqlExport};

require_once __DIR__ . '/../lib/BackupFile.php';
require_once __DIR__ . '/../lib/SqlExport.php';
require_once __DIR__ . '/../lib/PostgresqlExport.php';

function checkPostgresql($db, array $config, string $directory): void {
    $sql = <<<'SQL'
CREATE TABLE fixture (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message text NOT NULL UNIQUE, bytes bytea, payload jsonb, flag boolean,
  stamp timestamptz, generated integer GENERATED ALWAYS AS (length(message)) STORED
);
CREATE TABLE relation (id integer PRIMARY KEY, parent bigint REFERENCES fixture(id));
CREATE TABLE history_uint (id integer PRIMARY KEY, value text);
CREATE TABLE "odd.*""table" (id integer PRIMARY KEY, value text);
INSERT INTO fixture (message, bytes, payload, flag, stamp)
VALUES ('quote'' \ 中文😃', decode('00ff275c','hex'), '{"k":"value"}', true, '2026-01-01 15:00:00+05:30');
INSERT INTO relation VALUES (1,1);
INSERT INTO history_uint VALUES (1,'excluded history');
INSERT INTO "odd.*""table" VALUES (1,'literal table name');
SQL;
    if (!pg_query($db, $sql)) {
        throw new RuntimeException('Could not create PostgreSQL fixtures.');
    }
    $export = new PostgresqlExport($db, $config);
    if ($export->info()['type'] !== 'PostgreSQL' || !$export->info()['version']
            || !isset($export->tables()['fixture']['bytes'])) {
        throw new RuntimeException('PostgreSQL metadata missing.');
    }
    $cases = [
        'both' => [null, 'both', false],
        'schema' => [null, 'schema', false],
        'selected' => [['fixture'], 'both', false],
        'history' => [null, 'both', true],
        'data' => [['fixture'], 'data', false],
        'quoted' => [['odd.*"table'], 'both', false]
    ];
    foreach ($cases as $case => [$selected, $mode, $history]) {
        $file = fopen($directory . '/' . $case . '.sql', 'wb');
        try {
            $export->run(static function (string $chunk) use ($file): void {
                BackupFile::write($file, $chunk);
            }, $selected, $mode, $history);
        } finally {
            fclose($file);
        }
        $dump = file_get_contents($directory . '/' . $case . '.sql');
        if (strpos($dump, 'CREATE TABLE public.history_uint') === false) {
            throw new RuntimeException('Unselected/history table DDL missing.');
        }
        if (($mode === 'schema' || $case === 'history' || $case === 'selected' || $case === 'quoted')
                && strpos($dump, 'COPY public.history_uint') !== false) {
            throw new RuntimeException('Unselected/history data leaked.');
        }
        if (($case === 'data') !== (strpos($dump, 'CREATE TABLE public.fixture') === false)) {
            throw new RuntimeException('Wrong selected-table structure mode.');
        }
    }
    $file = fopen($directory . '/all-data.sql', 'wb');
    try {
        $export->run(static function (string $chunk) use ($file): void {
            BackupFile::write($file, $chunk);
        }, null, 'data');
    } finally {
        fclose($file);
    }
    $dump = file_get_contents($directory . '/all-data.sql');
    if (strpos($dump, 'CREATE ') !== false || strpos($dump, 'COPY public.fixture') === false) {
        throw new RuntimeException('All-table data mode included structure or omitted rows.');
    }
    try {
        $export->run(static function (): void {}, ['missing'], 'both');
        throw new LogicException('Invalid PostgreSQL table accepted.');
    } catch (RuntimeException $error) {
        if (strpos($error->getMessage(), 'selection') === false) {
            throw $error;
        }
    }
    if (pg_transaction_status($db) !== PGSQL_TRANSACTION_IDLE) {
        throw new RuntimeException('Export left a transaction open.');
    }
}
